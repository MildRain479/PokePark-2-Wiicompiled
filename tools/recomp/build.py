"""Builds the recompiled code, the test harness and the boot harness.

Usage:
    python tools/recomp/build.py                 # build both targets
    python tools/recomp/build.py --run test      # ...and run the tests
    python tools/recomp/build.py --run boot      # ...and boot main.dol
    python tools/recomp/build.py --release       # optimize across files (MSVC
                                                 # /GL /LTCG): a few % faster,
                                                 # each build ~70 s
    python tools/recomp/build.py --release --dist  # ...and put the game program
                                                 # in build/recomp/dist
    python tools/recomp/build.py --release --pgo --dist  # ...optimized with a
                                                 # profile of a run through
                                                 # the park (MSVC): ~8% less
                                                 # time per frame
    python tools/recomp/build.py --public        # a release build without the
                                                 # debug settings menu, put
                                                 # together in Releases/ for
                                                 # publishing (boot.exe is
                                                 # the public one until the
                                                 # next build)

Uses MSVC on Windows (found through vswhere) and cc elsewhere.
"""

import argparse
import glob
import shutil
import os
import subprocess
import sys

ROOT = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", ".."))
OUT = os.path.join(ROOT, "build", "recomp")
GEN = os.path.join(OUT, "gen")
OBJ = os.path.join(OUT, "obj")
DOL = os.path.join(ROOT, "orig", "R8AE01", "sys", "main.dol")
if not os.path.exists(DOL):  # only the disc extracted (dtk disc extract)
    DOL = os.path.join(ROOT, "orig", "R8AE01", "disc", "sys", "main.dol")

TARGETS = {
    "test": [
        os.path.join(ROOT, "recomp", "tests", "test_recomp.cpp"),
        # Decompiled game code, built natively as the reference.
        os.path.join(ROOT, "src", "flib", "CodepointConvert.cpp"),
        os.path.join(ROOT, "src", "flib", "FName.cpp"),
    ],
    "boot": sorted(glob.glob(os.path.join(ROOT, "recomp", "boot", "*.c")) +
                   glob.glob(os.path.join(ROOT, "recomp", "gpu", "*.c"))),
}
LIBS = {"boot": ["opengl32.lib", "user32.lib", "gdi32.lib", "ole32.lib", "windowscodecs.lib"]}
DEFINES = ["RECOMP_TRACE", "RECOMP_DEBUG_MENU"]
VULKAN = None  # the Vulkan SDK's folder, if there is one (vulkan_sdk)


def vcvars():
    vswhere = os.path.join(os.environ.get("ProgramFiles(x86)", r"C:\Program Files (x86)"),
                           "Microsoft Visual Studio", "Installer", "vswhere.exe")
    path = subprocess.check_output([vswhere, "-latest", "-products", "*", "-property", "installationPath"],
                                   text=True).strip()
    return os.path.join(path, "VC", "Auxiliary", "Build", "vcvars64.bat")


def stale(src, obj):
    return not os.path.exists(obj) or os.path.getmtime(obj) < os.path.getmtime(src)


# The Vulkan SDK (VULKAN_SDK, else the newest in C:\VulkanSDK): its headers
# and glslc, for the Vulkan device (vk_backend.c). The game loads Vulkan
# itself and needs none of it to run. Without it the device is left out.
def vulkan_sdk():
    sdk = os.environ.get("VULKAN_SDK")
    if not sdk and os.name == "nt":
        found = sorted(glob.glob(r"C:\VulkanSDK\*"), key=lambda d: [int(x) for x in os.path.basename(d).split(".")
                                                                    if x.isdigit()])
        sdk = found[-1] if found else None
    return sdk if sdk and os.path.exists(os.path.join(sdk, "Include", "vulkan", "vulkan.h")) else None


# The Vulkan shaders, compiled to SPIR-V as C arrays in gen/vk_shaders.h
# when one changed (and vk_backend.c with it).
def vulkan_shaders(sdk):
    srcs = sorted(glob.glob(os.path.join(ROOT, "recomp", "gpu", "vk_shaders", "*.*")))
    out = os.path.join(GEN, "vk_shaders.h")
    if os.path.exists(out) and all(os.path.getmtime(s) <= os.path.getmtime(out) for s in srcs):
        return
    glslc = os.path.join(sdk, "Bin", "glslc.exe" if os.name == "nt" else "glslc")
    parts = ["/* Generated by tools/recomp/build.py from recomp/gpu/vk_shaders. */\n"]
    for src in srcs:
        name = "kSpv_" + os.path.basename(src).replace(".", "_")
        code = subprocess.check_output([glslc, "--target-env=vulkan1.3", "-O", "-mfmt=c", "-o", "-", src], text=True)
        parts.append(f"static const uint32_t {name}[] = {code.strip()};\n")
    with open(out, "w") as f:
        f.write("".join(parts))
    for o in glob.glob(os.path.join(OBJ, "**", "vk_backend.o*"), recursive=True):
        os.remove(o)


def build_msvc(common, targets, opt):
    inc = (f'/I"{os.path.join(ROOT, "recomp", "runtime")}" /I"{GEN}" /I"{os.path.join(ROOT, "src")}" '
           f'/I"{os.path.join(ROOT, "recomp", "gpu")}"')
    if VULKAN:
        inc += f' /I"{os.path.join(VULKAN, "Include")}"'
    defs = " ".join(f"/D{d}" for d in DEFINES)
    # The generated code relies on wrapping unsigned arithmetic only.
    flags = f"/nologo {opt} /MP /W0 /fp:precise /Zi {defs} {inc}"
    bat = os.path.join(OUT, "build.bat")
    objdir = OBJ
    with open(bat, "w") as f:
        f.write(f'@call "{vcvars()}" >nul 2>nul\n')

        def compile_(srcs, odir, lang):
            os.makedirs(odir, exist_ok=True)
            todo = [s for s in srcs if stale(s, os.path.join(odir, os.path.splitext(os.path.basename(s))[0] + ".obj"))]
            if todo:
                extra = "/TC" if lang == "c" else "/TP /EHsc /std:c++17"
                f.write(f'cl {flags} {extra} /Fd"{odir}\\\\" /Fo"{odir}\\\\" /c ' +
                        " ".join(f'"{s}"' for s in todo) + " || exit /b 1\n")

        compile_(common, objdir, "c")
        for name, srcs in targets.items():
            tdir = os.path.join(objdir, name)
            compile_([s for s in srcs if s.endswith(".c")], tdir, "c")
            compile_([s for s in srcs if not s.endswith(".c")], tdir, "cpp")
            exe = os.path.join(OUT, name + ".exe")
            libs = " ".join(LIBS.get(name, []))
            ltcg = "/LTCG" if "/GL" in opt else ""
            f.write(f'link /nologo /DEBUG /PDBALTPATH:%%_PDB%% /MANIFEST:EMBED {ltcg} /OUT:"{exe}" "{objdir}\\*.obj" "{tdir}\\*.obj" {libs} || exit /b 1\n')
    subprocess.check_call(["cmd", "/c", bat])


# Profile-guided optimization (MSVC): the boot program linked instrumented,
# run through the park (the title, a save file, into the park and walking
# about) to see which code runs most, and linked again with that. The
# profile is kept in build/recomp/pgo and used by later builds (code that
# changed since goes without) until --pgo-train makes a new one.
def pgo_script():
    # Slowly: the instrumented program runs at about 15 fps.
    sc = [f"{t}:2 {t}.5:" for t in range(20, 141, 12)]
    t = 150
    for d in "up up+left up right up down+right up left up right up down up+left up right up".split():
        sc.append(f"{t}:{d}")
        t += 8
    return " ".join(sc)


def pgo(train):
    pgo_dir = os.path.join(OUT, "pgo")
    pgd = os.path.join(pgo_dir, "boot.pgd")
    objs = f'"{os.path.join(OBJ, "*.obj")}" "{os.path.join(OBJ, "boot", "*.obj")}"'
    libs = " ".join(LIBS["boot"])
    bat = os.path.join(pgo_dir, "link.bat")

    def link(mode, exe):
        with open(bat, "w") as f:
            f.write(f'@call "{vcvars()}" >nul 2>nul\n')
            f.write(f'link /nologo /DEBUG /PDBALTPATH:%%_PDB%% /MANIFEST:EMBED /LTCG:{mode} /PGD:"{pgd}" /OUT:"{exe}" {objs} {libs} '
                    "|| exit /b 1\n")
        subprocess.check_call(["cmd", "/c", bat])

    os.makedirs(pgo_dir, exist_ok=True)
    if train or not glob.glob(os.path.join(pgo_dir, "boot!*.pgc")):
        if not os.path.exists(DOL):
            print("pgo: no game in orig/R8AE01 to train with; linked without a profile")
            return
        for f in glob.glob(os.path.join(pgo_dir, "boot!*.pgc")):
            os.remove(f)
        exe = os.path.join(pgo_dir, "boot.exe")
        link("PGINSTRUMENT", exe)
        # The instrumented program needs the profiling runtime beside it.
        with open(bat, "w") as f:
            f.write(f'@call "{vcvars()}" >nul 2>nul\nwhere pgort140.dll\n')
        runtime = subprocess.check_output(["cmd", "/c", bat], text=True).split("\n")[0].strip()
        shutil.copy2(runtime, pgo_dir)
        shutil.copytree(os.path.join(ROOT, "recomp", "assets", "prompts"), os.path.join(pgo_dir, "prompts"),
                        dirs_exist_ok=True)
        nand = os.path.join(pgo_dir, "nand")
        shutil.rmtree(nand, ignore_errors=True)
        shutil.copytree(os.path.join(ROOT, "orig", "R8AE01", "nand"), nand)
        env = dict(os.environ, RECOMP_NAND=nand, RECOMP_SKIP_MOVIES="1", RECOMP_GX_HIDDEN="1", RECOMP_AUDIO="0",
                   RECOMP_SETTINGS=os.path.join(pgo_dir, "settings.ini"), RECOMP_PAD_SCRIPT=pgo_script())
        print("pgo: training, about 5 minutes")
        subprocess.call([exe, DOL, "290"], env=env, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
        shutil.rmtree(nand, ignore_errors=True)
        # Only the profile is kept: the instrumented program is ~70 MB with its symbols.
        for f in ("boot.exe", "boot.pdb", "boot.ilk"):
            if os.path.exists(os.path.join(pgo_dir, f)):
                os.remove(os.path.join(pgo_dir, f))
    link("PGOPTIMIZE", os.path.join(OUT, "boot.exe"))


def build_cc(common, targets, opt):
    inc = ["-I", os.path.join(ROOT, "recomp", "runtime"), "-I", GEN, "-I", os.path.join(ROOT, "src")]
    defs = [f"-D{d}" for d in DEFINES]
    objdir = OBJ

    def compile_(srcs, odir):
        os.makedirs(odir, exist_ok=True)
        objs = []
        for s in srcs:
            o = os.path.join(odir, os.path.basename(s) + ".o")
            if stale(s, o):
                cmd = (["cc", "-std=c99"] if s.endswith(".c") else ["c++", "-std=c++17"])
                subprocess.check_call(cmd + [opt, "-g", "-w", "-c", s, "-o", o] + inc + defs)
            objs.append(o)
        return objs

    common_objs = compile_(common, objdir)
    for name, srcs in targets.items():
        objs = compile_(srcs, os.path.join(objdir, name))
        subprocess.check_call(["c++", "-o", os.path.join(OUT, name)] + common_objs + objs + ["-lm", "-lpthread"])


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--run", choices=sorted(TARGETS))
    ap.add_argument("--opt", default=None, help="optimization flag (default /O2 or -O2)")
    ap.add_argument("--release", action="store_true", help="whole-program optimization (MSVC /GL with /LTCG)")
    ap.add_argument("--pgo", action="store_true",
                    help="with --release: optimize the boot program with a profile of a run through the park")
    ap.add_argument("--pgo-train", action="store_true", help="with --pgo: make a new profile")
    ap.add_argument("--no-trace", action="store_true",
                    help="without the trace of recent calls (RECOMP_TRACE) kept for crash reports and RECOMP_CALLS")
    ap.add_argument("--public", action="store_true",
                    help="release build without the debug settings menu, put together in Releases/")
    ap.add_argument("--dist", action="store_true",
                    help="copy the boot program, as PokePark.exe, and its files to build/recomp/dist")
    ap.add_argument("args", nargs="*", help="extra arguments for --run")
    args = ap.parse_args()
    global OBJ
    if args.public:
        args.release = True
    if args.release:
        args.opt = "/O2 /GL" if os.name == "nt" else "-O2 -flto"
    # Objects built with other flags go elsewhere, so switching rebuilds.
    if args.opt and args.opt not in ("/O2", "-O2"):
        OBJ = os.path.join(OUT, "obj_" + "".join(ch for ch in args.opt if ch.isalnum()))
    if args.no_trace:
        DEFINES.remove("RECOMP_TRACE")
        OBJ += "_notrace"
    if args.public:
        DEFINES.remove("RECOMP_DEBUG_MENU")
        OBJ += "_public"

    global VULKAN
    VULKAN = vulkan_sdk()
    if VULKAN:
        DEFINES.append("RECOMP_VULKAN")
        vulkan_shaders(VULKAN)
    else:
        print("no Vulkan SDK: building without the Vulkan device")

    gen = sorted(glob.glob(os.path.join(GEN, "*.c")))
    if not gen:
        sys.exit("run tools/recomp/recomp.py first")
    common = gen + sorted(glob.glob(os.path.join(ROOT, "recomp", "runtime", "*.c")))
    common += sorted(glob.glob(os.path.join(ROOT, "recomp", "patches", "*.c")))
    # Headers aren't tracked; a changed header rebuilds everything.
    headers = (glob.glob(os.path.join(ROOT, "recomp", "runtime", "*.h")) + glob.glob(os.path.join(ROOT, "recomp", "gpu", "*.h")) +
               [os.path.join(GEN, "recomp_funcs.h")])
    newest = max(os.path.getmtime(h) for h in headers if os.path.exists(h))
    for o in glob.glob(os.path.join(OBJ, "**", "*.o*"), recursive=True):
        if os.path.getmtime(o) < newest:
            os.remove(o)
    if os.name == "nt":
        build_msvc(common, TARGETS, args.opt or "/O2")
        if args.pgo and args.release:
            pgo(args.pgo_train)
    else:
        build_cc(common, TARGETS, args.opt or "-O2")
    # The button prompt icons, beside the program (prompts_win32.c).
    shutil.copytree(os.path.join(ROOT, "recomp", "assets", "prompts"), os.path.join(OUT, "prompts"), dirs_exist_ok=True)
    if args.dist:
        # Started without arguments it finds the game in an R8AE01 folder
        # beside it or above it (boot.c), so this runs in place.
        dist = os.path.join(OUT, "dist")
        os.makedirs(dist, exist_ok=True)
        shutil.copy2(os.path.join(OUT, "boot.exe"), os.path.join(dist, "PokePark.exe"))
        shutil.copytree(os.path.join(OUT, "prompts"), os.path.join(dist, "prompts"), dirs_exist_ok=True)
        # decomp-toolkit, which the game's set-up screen extracts disc images with (import_win32.c).
        dtk = os.path.join(ROOT, "build", "tools", "dtk.exe")
        if os.path.exists(dtk):
            os.makedirs(os.path.join(dist, "tools"), exist_ok=True)
            shutil.copy2(dtk, os.path.join(dist, "tools", "dtk.exe"))
            shutil.copy2(os.path.join(ROOT, "recomp", "assets", "dtk_license.txt"), os.path.join(dist, "tools", "dtk_license.txt"))
        print("dist:", dist)
    if args.public:
        # What players download: the program, its icons, the disc reader and
        # a readme. Nothing of the game's.
        rel = os.path.join(ROOT, "Releases")
        os.makedirs(rel, exist_ok=True)
        for old in ("prompts", "tools"):
            shutil.rmtree(os.path.join(rel, old), ignore_errors=True)
        shutil.copy2(os.path.join(OUT, "boot.exe"), os.path.join(rel, "PokePark.exe"))
        shutil.copytree(os.path.join(ROOT, "recomp", "assets", "prompts"), os.path.join(rel, "prompts"))
        shutil.copy2(os.path.join(ROOT, "recomp", "assets", "release_readme.txt"), os.path.join(rel, "README.txt"))
        dtk = os.path.join(ROOT, "build", "tools", "dtk.exe")
        if os.path.exists(dtk):
            os.makedirs(os.path.join(rel, "tools"))
            shutil.copy2(dtk, os.path.join(rel, "tools", "dtk.exe"))
            shutil.copy2(os.path.join(ROOT, "recomp", "assets", "dtk_license.txt"), os.path.join(rel, "tools", "dtk_license.txt"))
        else:
            print("public: no build/tools/dtk.exe; the release can't read disc images without it")
        print("public:", rel)
    if args.run:
        exe = os.path.join(OUT, args.run + (".exe" if os.name == "nt" else ""))
        sys.exit(subprocess.call([exe, DOL] + args.args))


if __name__ == "__main__":
    main()
